# Writes assets/factory/install.luau from manifest.json (export.py). Run: python assets/factory/gen_install.py
# install.luau is run ONCE in Studio (edit mode, Studio MCP execute_luau or the command bar) after
# FactoryKit.glb is in the place (File > Import 3D, or uploaded as a Model): it takes out every MeshPart,
# gives each its colour / finish / place from the manifest and files it under ReplicatedStorage.FactoryKit/<Piece>.
# Factory.luau clones from there; with no FactoryKit it builds every machine from parts.
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
manifest = json.load(open(os.path.join(HERE, "manifest.json")))

rows = []
for piece, entries in sorted(manifest.items()):
    for e in entries:
        at = ", ".join(map(str, e["at"]))
        rows.append(f'\t["{e["name"]}"] = {{ "{piece}", "{e["color"]}", Vector3.new({at}), "{e["finish"]}" }},')

lua = f'''-- Generated by assets/factory/gen_install.py from manifest.json. Run once in Studio, in EDIT mode,
-- after FactoryKit.glb is on Roblox, either way:
--  * uploaded through Open Cloud as a Model: set MODEL_ID to its asset id;
--  * imported with Studio's File > Import 3D: leave MODEL_ID 0, the imported "FactoryKit" (or "Scene") in Workspace is used.
-- Then save the place. Each MeshPart gets a "Place" attribute: its CFrame in its piece's space.
local MODEL_ID = 0

local KIT = {{ -- [mesh name] = {{ piece, colour, its centre in the piece's space (studs), Roblox material }}
{chr(10).join(rows)}
}}

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local loaded = if MODEL_ID ~= 0 then game:GetObjects("rbxassetid://" .. MODEL_ID)[1] else workspace:FindFirstChild("FactoryKit") or workspace:FindFirstChild("Scene")
assert(loaded, "no FactoryKit: set MODEL_ID, or import FactoryKit.glb with File > Import 3D first")
local old = ReplicatedStorage:FindFirstChild("FactoryKit")
if old then
	old:Destroy()
end
local kit = Instance.new("Folder")
kit.Name = "FactoryKit"
local found, missing = 0, {{}}
for _, p in loaded:GetDescendants() do
	local info = p:IsA("MeshPart") and KIT[p.Name]
	if info then
		local folder = kit:FindFirstChild(info[1]) or Instance.new("Folder")
		folder.Name = info[1]
		folder.Parent = kit
		p.Name = info[2]
		p.Color = Color3.fromHex(info[2])
		p.Material = Enum.Material[info[4]] -- Plastic like the hall's bricks; chrome Metal, lava Neon
		p.Reflectance = if info[4] == "Metal" then 0.1 else 0
		p.CFrame = CFrame.identity
		-- decoration only: Factory.luau keeps its stand-in parts as the (invisible) collision and
		-- damage zones, and welds the moving pieces' meshes to them (unanchoring them as it does)
		p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch = true, false, false, false
		p.CollisionFidelity = Enum.CollisionFidelity.Box
		p.DoubleSided = true
		p.CastShadow = info[4] ~= "Neon"
		p.RenderFidelity = Enum.RenderFidelity.Precise -- the automatic LOD hollows thin shells at range
		-- where it sits in its piece's space. The importer turns every mesh 180 degrees about Y
		-- (measured on the army kit's helicopter beacon and nav light), so the place carries the turn back.
		p:SetAttribute("Place", CFrame.new(info[3]) * CFrame.Angles(0, math.pi, 0))
		p.Parent = folder
		found += 1
	end
end
for name in KIT do
	local piece = string.split(name, "__")[1]
	local colour = string.split(name, "__")[2]
	if not (kit:FindFirstChild(piece) and kit[piece]:FindFirstChild(colour)) then
		table.insert(missing, name)
	end
end
loaded:Destroy()
kit.Parent = ReplicatedStorage
return ("FactoryKit: %d of %d meshes in; missing: %s"):format(found, {sum(len(v) for v in manifest.values())}, table.concat(missing, ", "))
'''
open(os.path.join(HERE, "install.luau"), "w", newline="\n").write(lua)
print("install.luau:", len(rows), "meshes")
