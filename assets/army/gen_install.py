# Writes assets/army/install.luau from manifest.json (export.py). Run: python assets/army/gen_install.py
# install.luau is run ONCE in Studio (edit mode, Studio MCP execute_luau or the command bar) after
# ArmyKit.glb has been uploaded as a Model: it inserts that model, takes out every MeshPart, gives
# each its colour / finish / place from the manifest and files it under ReplicatedStorage.ArmyKit/<Piece>.
# The game (Outfits, Helicopter, DummyGear) clones from there; with no ArmyKit it builds from parts.
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
manifest = json.load(open(os.path.join(HERE, "manifest.json")))

rows = []
for piece, entries in sorted(manifest.items()):
    for e in entries:
        at = ", ".join(map(str, e["at"]))
        rows.append(f'\t["{e["name"]}"] = {{ "{piece}", "{e["color"]}", Vector3.new({at}), {str(e["neon"]).lower()}, {e["transparency"]} }},')

lua = f'''-- Generated by assets/army/gen_install.py from manifest.json. Run once in Studio, in EDIT mode,
-- after ArmyKit.glb is on Roblox, either way:
--  * uploaded through Open Cloud as a Model: set MODEL_ID to its asset id;
--  * imported with Studio's File > Import 3D: leave MODEL_ID 0, the imported "ArmyKit" in Workspace is used.
-- Then save the place. Each MeshPart gets a "Place" attribute: its CFrame in its piece's space.
-- MERGE true: the import holds only some pieces (e.g. PoliceCar.glb): those replace their folders and
-- the rest of the kit stays.
local MODEL_ID = 0
local MERGE = false

local KIT = {{ -- [mesh name] = {{ piece, colour, its centre in the piece's space (studs), neon, transparency }}
{chr(10).join(rows)}
}}

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local loaded = if MODEL_ID ~= 0 then game:GetObjects("rbxassetid://" .. MODEL_ID)[1] else workspace:FindFirstChild("ArmyKit") or workspace:FindFirstChild("Scene")
assert(loaded, "no ArmyKit: set MODEL_ID, or import ArmyKit.glb with File > Import 3D first")
local old = ReplicatedStorage:FindFirstChild("ArmyKit")
local kit = Instance.new("Folder")
kit.Name = "ArmyKit"
local found, missing, pieces = 0, {{}}, {{}}
for _, p in loaded:GetDescendants() do
	local info = p:IsA("MeshPart") and KIT[p.Name]
	if info then
		pieces[info[1]] = true
		local folder = kit:FindFirstChild(info[1]) or Instance.new("Folder")
		folder.Name = info[1]
		folder.Parent = kit
		p.Name = info[2]
		p.Color = Color3.fromHex(info[2])
		p.Material = info[4] and Enum.Material.Neon or Enum.Material.SmoothPlastic
		p.Transparency = info[5]
		p.CFrame = CFrame.identity
		p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.Massless = false, false, false, false, true
		p.CastShadow = false
		p.RenderFidelity = Enum.RenderFidelity.Precise -- the automatic LOD hollows the thin helmet domes at range
		-- where it sits in its piece's space. The importer turns every mesh 180 degrees about Y
		-- (measured on the helicopter's beacon and nav light), so the place carries the turn back.
		p:SetAttribute("Place", CFrame.new(info[3]) * CFrame.Angles(0, math.pi, 0))
		p.Parent = folder
		found += 1
	end
end
if MERGE and old then -- keep every piece this import did not bring
	for _, folder in old:GetChildren() do
		if not pieces[folder.Name] then
			folder.Parent = kit
		end
	end
end
if old then
	old:Destroy()
end
for name in KIT do
	local piece = string.split(name, "__")[1]
	local colour = string.split(name, "__")[2]
	if (not MERGE or pieces[piece]) and not (kit:FindFirstChild(piece) and kit[piece]:FindFirstChild(colour)) then
		table.insert(missing, name)
	end
end
loaded:Destroy()
kit.Parent = ReplicatedStorage
return ("ArmyKit: %d of %d meshes in; missing: %s"):format(found, {sum(len(v) for v in manifest.values())}, table.concat(missing, ", "))
'''
open(os.path.join(HERE, "install.luau"), "w", newline="\n").write(lua)
print("install.luau:", len(rows), "meshes")
