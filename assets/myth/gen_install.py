# Writes assets/myth/install.luau from manifest.json (blender/export_myth_kit.py).
# Run: python assets/myth/gen_install.py
# install.luau is run ONCE in Studio, in EDIT mode, after the three MythKit_<Kind>.glb files are on
# Roblox as Models. It files every MeshPart under ReplicatedStorage.MythKit/<Kind>/Boss/<RigPart> or
# MythKit/<Kind>/Cage/<Static|Gate>, gives it its colour, material and "Place" (its CFrame in boss
# space / cage space), and adds small "Light" parts carrying PointLights. MythRig and Monsters clone
# from there; with no MythKit they keep building the part-made monsters and bar cages.
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
manifest = json.load(open(os.path.join(HERE, "manifest.json")))


def v3(a):
    return "Vector3.new(%s)" % ", ".join(str(round(x, 4)) for x in a)


rows, lights, stands = [], [], []
for kind, data in sorted(manifest.items()):
    for section, key in (("Boss", "boss"), ("Cage", "cage")):
        for e in data[key]:
            rows.append(f'\t["{e["name"]}"] = {{ "{kind}", "{section}", "{e["group"]}", "{e["color"]}", "{e["material"]}", {v3(e["at"])} }},')
        for l in data[key + "_lights"]:
            lights.append(f'\t{{ "{kind}", "{section}", "{l["group"]}", "{l["color"]}", {v3(l["at"])}, {l["brightness"]}, {l["range"]} }},')
    stands.append(f'\t{kind} = {v3(data["stand"])},')

ID_FILE = os.path.join(HERE, "ids.json")  # asset ids of the uploaded GLBs
IDS = json.load(open(ID_FILE)) if os.path.exists(ID_FILE) else {}
ids = "\n".join(f'\t{k} = {IDS.get(k, 0)},' for k in sorted(manifest))
count = sum(len(d["boss"]) + len(d["cage"]) for d in manifest.values())
lua = f'''-- Generated by assets/myth/gen_install.py from manifest.json. Run once in Studio, in EDIT mode,
-- after the MythKit_<Kind>.glb files are on Roblox as Models: set MODEL_IDS to their asset ids (or
-- import them with File > Import 3D and leave the id 0: the imported model in Workspace is used).
-- Then save the place: ReplicatedStorage.MythKit is not part of the Rojo project.
local MODEL_IDS = {{
{ids}
}}

local KIT = {{ -- [mesh] = {{ kind, "Boss"/"Cage", rig part / Static / Gate, colour, material, box centre (studs) }}
{chr(10).join(rows)}
}}
local LIGHTS = {{ -- {{ kind, section, group, colour, place, brightness, range }}
{chr(10).join(lights)}
}}
local STANDS = {{ -- where the boss's feet are, in cage space
{chr(10).join(stands)}
}}

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local old = ReplicatedStorage:FindFirstChild("MythKit")
if old then
	old:Destroy()
end
local kit = Instance.new("Folder")
kit.Name = "MythKit"
local function folder(parent, name)
	local f = parent:FindFirstChild(name) or Instance.new("Folder")
	f.Name = name
	f.Parent = parent
	return f
end
local found, loaded = 0, {{}}
for kind, id in MODEL_IDS do
	local model = if id ~= 0 then game:GetObjects("rbxassetid://" .. id)[1] else workspace:FindFirstChild("MythKit_" .. kind)
	assert(model, "no model for " .. kind .. ": set MODEL_IDS, or import MythKit_" .. kind .. ".glb first")
	table.insert(loaded, model)
	local cage = folder(folder(kit, kind), "Cage")
	cage:SetAttribute("Stand", STANDS[kind])
	folder(kit[kind], "Boss")
end
for _, model in loaded do
	for _, p in model:GetDescendants() do
		local info = p:IsA("MeshPart") and KIT[p.Name]
		if info then
			p.Parent = folder(kit[info[1]][info[2]], info[3])
			p.Color = Color3.fromHex(info[4])
			p.Material = Enum.Material[info[5]]
			p.CFrame = CFrame.identity
			p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.Massless = true, false, false, false, true
			p.CastShadow = p.Size.Magnitude > 3
			-- the importer turns every mesh 180 degrees about Y (see assets/army/install.luau)
			p:SetAttribute("Place", CFrame.new(info[6]) * CFrame.Angles(0, math.pi, 0))
			found += 1
		end
	end
	model:Destroy()
end
for _, l in LIGHTS do
	local p = Instance.new("Part")
	p.Name, p.Size, p.Transparency = "Light", Vector3.one * 0.2, 1
	p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.Massless, p.CastShadow = true, false, false, false, true, false
	p:SetAttribute("Place", CFrame.new(l[5]))
	local light = Instance.new("PointLight")
	light.Color, light.Brightness, light.Range, light.Shadows = Color3.fromHex(l[4]), l[6], l[7], false
	light.Parent = p
	p.Parent = folder(kit[l[1]][l[2]], l[3])
end
kit.Parent = ReplicatedStorage
return ("MythKit: %d of {count} meshes in, %d lights"):format(found, #LIGHTS)
'''
open(os.path.join(HERE, "install.luau"), "w", newline="\n").write(lua)
print("install.luau:", len(rows), "meshes,", len(lights), "lights")
