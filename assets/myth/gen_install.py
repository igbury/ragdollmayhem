# Writes assets/myth/install.luau from manifest.json (export_bosses.py). Run: python assets/myth/gen_install.py
# install.luau is run ONCE in Studio, in EDIT mode, after MythKit.glb is on Roblox (uploaded as a Model, or
# imported with File > Import 3D). It files every MeshPart under ReplicatedStorage.MythKit:
#   <Kind>/Boss/<RigPart>   the body, "Place" = its CFrame in rig space, rest pose, before Model:ScaleTo
#   <Kind>/Lair/Pylon       the pylons either side of the lair's way out, "Place" in the pylon's space
#   Chain/Parts/<Link|Anchor>  the chains that hold a boss in its pit
# MythRig dresses the part rig from Boss; Monsters builds pylons and chains from the rest. With no MythKit
# both keep their part-made fallbacks.
import json
import os

HERE = os.path.dirname(os.path.abspath(__file__))
manifest = json.load(open(os.path.join(HERE, "manifest.json")))


def v3(a):
    return "Vector3.new(%s)" % ", ".join(str(round(x, 4)) for x in a)


rows = []
for piece, entries in sorted(manifest.items()):
    for e in entries:
        rows.append(f'\t["{e["name"]}"] = {{ "{e["kind"]}", "{e["section"]}", "{e["group"]}", "{e["color"]}", {str(e["neon"]).lower()}, {v3(e["at"])} }},')

ID_FILE = os.path.join(HERE, "ids.json")  # asset id of the uploaded MythKit.glb
IDS = json.load(open(ID_FILE)) if os.path.exists(ID_FILE) else {}
count = len(rows)
lua = f'''-- Generated by assets/myth/gen_install.py from manifest.json. Run once in Studio, in EDIT mode, after
-- MythKit.glb is on Roblox, either way:
--  * uploaded through Open Cloud as a Model: MODEL_ID is its asset id;
--  * imported with Studio's File > Import 3D: set MODEL_ID 0, the imported "MythKit" (or "Scene") in Workspace is used.
-- Then save the place: ReplicatedStorage.MythKit is not part of the Rojo project.
local MODEL_ID = {IDS.get("MythKit", 0)}

local KIT = {{ -- [mesh] = {{ kind, section, group, colour, neon, box centre in its group's space (studs) }}
{chr(10).join(rows)}
}}

local ReplicatedStorage = game:GetService("ReplicatedStorage")
local loaded = if MODEL_ID ~= 0 then game:GetObjects("rbxassetid://" .. MODEL_ID)[1] else workspace:FindFirstChild("MythKit") or workspace:FindFirstChild("Scene")
assert(loaded, "no MythKit: set MODEL_ID, or import MythKit.glb with File > Import 3D first")
local old = ReplicatedStorage:FindFirstChild("MythKit")
if old then
	old:Destroy()
end
local kit = Instance.new("Folder")
kit.Name = "MythKit"
local function folder(parent, name)
	local f = parent:FindFirstChild(name) or Instance.new("Folder")
	f.Name = name
	f.Parent = parent
	return f
end
local found, missing, seen = 0, {{}}, {{}}
for _, p in loaded:GetDescendants() do
	local info = p:IsA("MeshPart") and KIT[p.Name]
	if info then
		seen[p.Name] = true
		p.Parent = folder(folder(folder(kit, info[1]), info[2]), info[3])
		p.Color = Color3.fromHex(info[4])
		p.Material = if info[5] then Enum.Material.Neon else Enum.Material.SmoothPlastic
		p.CFrame = CFrame.identity
		p.Anchored, p.CanCollide, p.CanQuery, p.CanTouch, p.Massless = true, false, false, false, true
		-- the black inverted hulls (cartoon outlines) and the glows cast no shadow
		p.CastShadow = not info[5] and info[4] ~= "000000"
		-- the importer turns every mesh 180 degrees about Y (see assets/army/install.luau)
		p:SetAttribute("Place", CFrame.new(info[6]) * CFrame.Angles(0, math.pi, 0))
		found += 1
	end
end
for name in KIT do
	if not seen[name] then
		table.insert(missing, name)
	end
end
loaded:Destroy()
kit.Parent = ReplicatedStorage
return ("MythKit: %d of {count} meshes in; missing: %s"):format(found, table.concat(missing, ", "))
'''
open(os.path.join(HERE, "install.luau"), "w", newline="\n").write(lua)
print("install.luau:", len(rows), "meshes, MODEL_ID", IDS.get("MythKit", 0))
